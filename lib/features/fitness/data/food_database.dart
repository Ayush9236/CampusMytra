  // ── Convenience getters ───────────────────────────────────────────────────

  static List<FoodItem> forMeal(String meal) =>
      all.where((f) => f.meals.contains(meal) || f.meals.contains('any')).toList();

  static List<FoodItem> search(String query) {
    final q = query.toLowerCase().trim();
    if (q.isEmpty) return all;
    return all.where((f) => f.name.toLowerCase().contains(q)).toList();
  }

  /// Returns up to [limit] foods sorted descending by the value returned
  /// by [selector], excluding foods whose ids are in [excludeIds].
  static List<FoodItem> topBy({
    required double Function(FoodItem) selector,
    required Set<String> excludeIds,
    int limit = 3,
  }) {
    final candidates = all.where((f) => !excludeIds.contains(f.id)).toList()
      ..sort((a, b) => selector(b).compareTo(selector(a)));
    return candidates.take(limit).toList();
  }
