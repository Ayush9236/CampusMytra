/// A single food item with nutritional values per serving.
class FoodItem {
  final String id;
  final String name;
  final String emoji;

  /// One of: 'grain' | 'protein' | 'dairy' | 'vegetable' | 'fruit' |
  /// 'legume' | 'snack' | 'beverage'
  final String category;

  /// e.g. ['breakfast'] or ['lunch','dinner'] or ['snacks'] or ['any']
  final List<String> meals;

  final double servingGrams;

  /// Human-readable label, e.g. "1 bowl (150g)"
  final String servingLabel;

  // ── Nutrients PER SERVING (not per 100 g) ──────────────────────────────────
  final double calories;
  final double proteinG;
  final double carbsG;
  final double fatG;
  final double fiberG;
  final double calciumMg;
  final double ironMg;
  final double vitaminCMg;
  final double? vitaminB12Mcg; // nullable — absent in many plant foods
  final double? zincMg; // nullable

  const FoodItem({
    required this.id,
    required this.name,
    required this.emoji,
    required this.category,
    required this.meals,
    required this.servingGrams,
    required this.servingLabel,
    required this.calories,
    required this.proteinG,
    required this.carbsG,
    required this.fatG,
    required this.fiberG,
    required this.calciumMg,
    required this.ironMg,
    required this.vitaminCMg,
    this.vitaminB12Mcg,
    this.zincMg,
  });
}

